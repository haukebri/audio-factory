// Deterministic UI lifecycle check against the owned --offline Studio fixture.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const manifest = JSON.parse(readFileSync('.test-artifacts/studio-youtube-offline-session.json'));
assert.equal(manifest.fixture, true);
const session = 'youtube-lifecycle';
const run = (...args) => {
  if (args[0] === 'click') args = ['eval', `document.querySelector(${JSON.stringify(args[1])}).click()`];
  const result = JSON.parse(execFileSync('agent-browser', ['--session', session, '--json', ...args], { encoding: 'utf8', timeout: 60000, env: { ...process.env, AGENT_BROWSER_DEFAULT_TIMEOUT: '50000' } }));
  assert.ok(result.success, result.error); return result.data;
};
const evaluate = code => run('eval', code).result;
const wait = code => { try { return run('wait', '--fn', code); } catch (error) { console.error('UI state:', evaluate('({status:document.querySelector("#status")?.textContent,open:document.querySelector("#youtube-dialog")?.open,progress:document.querySelector("#youtube-progress")?.textContent,error:document.querySelector("#youtube-error")?.textContent,context:typeof youtube === "undefined" ? null : youtube,storage:Object.fromEntries(Object.keys(localStorage).map(k=>[k,localStorage[k]]))})')); throw error; } };
const call = async (path, value) => {
  const r = await fetch(manifest.url + '/studio/' + path, { headers: { Connection: 'close', Authorization: 'Bearer youtube-review-fixture', 'Content-Type': 'application/json' }, ...(value === undefined ? {} : { method: 'POST', body: JSON.stringify(value) }) });
  assert.ok(r.ok, await r.clone().text()); return r.json();
};
const reload = () => { const previous = evaluate('performance.timeOrigin'); run('reload'); wait(`performance.timeOrigin !== ${previous} && document.querySelector('#status')?.textContent.startsWith('Connected')`); };
const base = `batches/${manifest.batch_id}`;
const evidence = { ...manifest };
try {
  run('open', `${manifest.url}/#batch/${manifest.batch_id}`);
  wait('document.querySelectorAll("[data-take]").length === 5');
  evaluate(`document.querySelector('#batch-prompt-editor').open=true;`);
  run('fill', '#batch-prompt', 'Unsaved discovery words'); run('select', '#batch-duration', '10'); run('check', '#batch-loop');
  run('click', '#batch-youtube');
  assert.equal(evaluate('document.querySelector("#youtube-query").value'), 'Unsaved discovery words');
  assert.equal(evaluate('document.querySelectorAll(".youtube-result").length'), 0);
  run('press', 'Escape'); wait('!document.querySelector("#youtube-dialog").open');
  assert.equal(evaluate('document.activeElement.id'), 'batch-youtube');
  run('click', '#batch-youtube'); run('fill', '#youtube-url', 'https://www.youtube.com/watch?v=CBDZg1Jb_T4'); run('fill', '#youtube-start', '120'); run('fill', '#youtube-end', '125');
  await call(base + '/pause', {});
  evaluate(`(() => { const original=window.fetch; window.fetch=async (...args)=>{const r=await original(...args);if(String(args[0]).endsWith('/youtube')&&args[1]?.method==='POST'){window.fetch=original;await r.json();window.lostImportAcceptance=true;throw new TypeError('Controlled lost acceptance');}return r;}; })()`);
  run('click', '#youtube-add'); wait('window.lostImportAcceptance');
  const pending = evaluate(`JSON.parse(localStorage.getItem('studio-youtube-${manifest.batch_id}:rain')).pending`);
  assert.ok(pending.key);
  run('click', '#youtube-close'); assert.equal(evaluate('document.querySelectorAll("iframe").length'), 0);
  reload(); run('snapshot', '-i'); run('click', '#batch-youtube');
  wait('!document.querySelector("#youtube-cancel").hidden');
  assert.equal(evaluate('document.querySelector("#youtube-start").value'), '120');
  assert.equal((await call(base)).sounds[0].operations.length, 2);
  run('click', '#youtube-cancel'); wait('document.querySelector("#youtube-progress").textContent.startsWith("canceled")');
  assert.equal((await call(base)).sounds[0].operations.at(-1).status, 'canceled');
  await call(base + '/resume', {});
  run('click', '#youtube-add'); wait('document.querySelector("#youtube-progress").textContent.includes("Importing audio")');
  run('click', '#youtube-close');
  evaluate(`[...document.querySelectorAll('#sound-list button')].find(b=>b.dataset.soundKey==='gate').click()`);
  run('click', '#batch-youtube');
  wait(`document.querySelector('#status').textContent.includes('YouTube audio added to rain')`);
  assert.equal(evaluate('document.querySelector("#youtube-dialog").open'), true);
  assert.equal(evaluate('document.querySelector("#youtube-target").textContent'), 'gate');
  run('click', '#youtube-close');
  evaluate(`[...document.querySelectorAll('#sound-list button')].find(b=>b.dataset.soundKey==='rain').click()`);
  wait('document.querySelectorAll("[data-take]").length===6');
  assert.equal(evaluate('document.querySelector("#batch-prompt").value'), 'Unsaved discovery words');
  assert.equal(evaluate('document.querySelector("#batch-duration").value'), '10');
  assert.equal(evaluate('document.querySelector("#batch-loop").checked'), true);
  run('click', '#batch-youtube'); run('fill', '#youtube-start', '1.25'); run('fill', '#youtube-end', '3.75');
  run('click', '#youtube-add'); wait('document.querySelector("#youtube-progress").textContent.includes("Importing audio")');
  reload(); run('snapshot', '-i'); run('click', '#batch-youtube');
  wait('!document.querySelector("#youtube-cancel").hidden');
  assert.equal(evaluate('document.querySelector("#youtube-start").value'), '1.25');
  wait('!document.querySelector("#youtube-dialog").open && document.querySelectorAll("[data-take]").length===7');
  evidence.titles = evaluate('[...document.querySelectorAll("[data-take] h4")].map(e=>e.textContent)');
  assert.ok(evidence.titles.some(t=>t.includes('Clip 7 · YouTube')));
  run('click', '#batch-youtube'); run('click', '#youtube-add');
  wait('document.querySelector("#youtube-progress").textContent.includes("Importing audio")'); run('click', '#youtube-cancel');
  wait('document.querySelector("#youtube-progress").textContent.startsWith("canceled")');
  run('click', '#youtube-close'); assert.equal(evaluate('document.querySelectorAll("[data-take]").length'), 7);
  run('set', 'viewport', '390', '844'); run('click', '#batch-youtube'); run('click', '#youtube-search');
  wait('document.querySelectorAll(".youtube-result").length===1');
  assert.equal(evaluate('document.documentElement.scrollWidth > innerWidth'), false);
  assert.ok(evaluate('document.querySelector("iframe").getBoundingClientRect().height') >= 200);
  run('press', 'Escape'); assert.equal(evaluate('document.querySelectorAll("iframe").length'), 0);
  evidence.batch = await call(base);
  writeFileSync('.test-artifacts/youtube-browser-lifecycle.json', JSON.stringify(evidence, null, 2));
  console.log('Passed popup drafts/focus, uncertain acceptance, queued/active cancel, refresh, original ownership, view preservation, numbering and mobile layout.');
} finally { run('close'); }
